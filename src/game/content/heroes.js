export const heroes = Object.fromEntries(
  configurations.map((entry) => {
    const [
      id,
      campaignId,
      theme,
      hp,
      attack,
      defense,
      magic,
      symbols,
      itinerary,
      boss,
      ability,
      effect,
    ] = entry
    const route = itinerary.split(' ')
    const pool = symbols.split(' ').map((id, index) => ({
      id,
      weight: [7, 23, 20, 18, 17, 15][index],
      effect: effects[index],
    }))
    return [
      id,
      {
        id,
        campaignId,
        nameKey: `heroes.${id}.name`,
        descriptionKey: `heroes.${id}.description`,
        portrait: `/art/${id}.webp`,
        theme,
        stats: { hp, attack, defense, magic },
        abilities: [
          {
            id: ability,
            cost: 4,
            cooldown: 3,
            effect: { ...effect, damage: Math.ceil(effect.damage / 2) },
          },
        ],
        artifacts: ['waystone'],
        slotConfig: { pool },
        jackpot: { symbol: pool[0].id, count: 3, effect },
        startingLocationId: route[0],
        storyId: id,
        route,
        boss,
        progression: { xpStep: 75, hpPerLevel: 5 },
      },
    ]
  })
)

export const getHeroes = (campaignId) =>
  Object.values(heroes).filter((hero) => hero.campaignId === campaignId)
